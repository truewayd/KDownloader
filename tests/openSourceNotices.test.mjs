import test from "node:test";
import assert from "node:assert/strict";
import { readFile } from "node:fs/promises";
import { openSourceNotices } from "../truedown/tools/open-source-notices.mjs";

test("packaged About references retain original licenses and the generated mirror", async () => {
  const notices = await openSourceNotices();
  const source = await readFile(new URL("../truedown/web/open-source.js", import.meta.url), "utf8");
  assert.equal(source.replace(/\r\n/g, "\n"), `// Generated by tools/open-source-notices.mjs.\nwindow.TrueDownOpenSource = ${JSON.stringify(notices)};\n`);
  assert.match(notices.notices, /Permission is hereby granted, free of charge/);
  assert.match(notices.notices, /MEGAcmdShell/);
  assert.match(notices.notices, /GNU GENERAL PUBLIC LICENSE/);
  for (const name of ["gdown", "MEGAJS", "MEGA SDK", "MEGAcmd"]) {
    const reference = notices.projects.find(project => project.name === name);
    assert.ok(reference && /\/tree\/[a-f0-9]{40}$/.test(reference.url), `${name} must identify its reviewed source`);
  }
});

import { promises as fs } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { createHash } from "node:crypto";

const project = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
export async function openSourceNotices() {
  const projects = JSON.parse(await fs.readFile(path.join(project, "licenses/projects.json"), "utf8"));
  const parts = [await fs.readFile(path.join(project, "THIRD_PARTY_NOTICES.md"), "utf8")];
  for (const entry of projects) {
    if (!entry.file) continue;
    if (!/^[A-Za-z_]+\.txt$/.test(entry.file)) throw new Error("Invalid reference notice filename");
    const data = await fs.readFile(path.join(project, "licenses", entry.file));
    if (createHash("sha256").update(data).digest("hex") !== entry.sha256) throw new Error(`Reference license changed: ${entry.name}`);
    parts.push(`${entry.name} — ${entry.license}\nSource: ${entry.url}\n\n${data.toString("utf8")}`);
  }
  parts.push(`GNU General Public License v2 (aria2 / Aria2 Next)\n\n${await fs.readFile(path.join(project, "ARIA2_COPYING"), "utf8")}`);
  parts.push(`Project license / GPL v3 (RatioGhost reference)\n\n${await fs.readFile(path.join(project, "../LICENSE"), "utf8")}`);
  return { projects: projects.map(({file,sha256,...entry}) => entry), notices: parts.map(text => text.replace(/\r\n/g,"\n")).join("\n\n") };
}
if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const data = `// Generated by tools/open-source-notices.mjs.\nwindow.TrueDownOpenSource = ${JSON.stringify(await openSourceNotices())};\n`;
  const destination = path.join(project, "web/open-source.js");
  if (process.argv.includes("--check")) {
    if ((await fs.readFile(destination, "utf8")).replace(/\r\n/g,"\n") !== data.replace(/\r\n/g,"\n")) throw new Error("Run node truedown/tools/open-source-notices.mjs");
  } else { await fs.writeFile(destination,data); }
  console.log("Open-source reference notices verified");
}
